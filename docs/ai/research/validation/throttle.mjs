import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', headless: false, args: ['--headless=new'] })
const ctx = await browser.newContext()
const a = await ctx.newPage()
await a.setContent('<script>window.ticks=0;window.gaps=[];let last=performance.now();setInterval(()=>{const n=performance.now();window.gaps.push(n-last);last=n;window.ticks++},100)</script>')
await a.waitForTimeout(3000)
const fg = await a.evaluate(() => ({ ticks: window.ticks, vis: document.visibilityState }))
const b = await ctx.newPage()
await b.bringToFront()
await a.evaluate(() => { window.ticks = 0; window.gaps = [] })
await b.waitForTimeout(15000)
const bg = await a.evaluate(() => { const g = [...window.gaps].sort((x, y) => x - y); return { ticks: window.ticks, vis: document.visibilityState, gapP50: Math.round(g[Math.floor(g.length / 2)] ?? 0), gapMax: Math.round(g.at(-1) ?? 0) } })
console.log(JSON.stringify({ foreground3s: fg, background15s: bg }))
await browser.close()
